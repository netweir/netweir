def suffix(domain: str) -> str:
    parts = domain.split(".")
    if len(parts) > 2 and parts[-2] in SECOND_LEVEL:
        return ".".join(parts[-2:])
    return parts[-1]


def pick(rows: list[tuple[int, str]]) -> list[tuple[int, str]]:
    by_suffix = defaultdict(list)
    for rank, domain in rows:
        if rank <= TOP and not any(word in domain for word in SKIP):
            by_suffix[suffix(domain)].append((rank, domain))
    # The scale that makes the shares add up to PICKS, found by bisection.
    lo, hi = 0.0, 100.0
    for _ in range(50):
        c = (lo + hi) / 2
        total = sum(min(len(v), CAP, math.ceil(c * math.sqrt(len(v)))) for v in by_suffix.values())
        lo, hi = (c, hi) if total < PICKS else (lo, c)
    out = []
    for domains in by_suffix.values():
        out += domains[: min(CAP, math.ceil(lo * math.sqrt(len(domains))))]
    return sorted(out)


