"""Writes src/distrust_after.rs: Mozilla's roots that Firefox stops
trusting for certificates issued after a date (CKA_NSS_SERVER_DISTRUST_AFTER
in NSS's certdata.txt).

    python3 scripts/gen-distrust-after.py NSS_3_133_RTM

The argument is the NSS release tag whose certdata.txt to read, from the
nss-dev/nss mirror on GitHub; a path to a certdata.txt works too. Use the
tag of the NSS that the Firefox profiles' release ships (Firefox 161:
NSS 3.133), the one webpki-root-certs' roots are checked against
(src/roots.rs).
"""

import calendar
import hashlib
import os
import sys
import urllib.request

source = sys.argv[1]
if os.path.exists(source):
    with open(source, encoding="utf-8") as f:
        text = f.read()
    origin = "a local certdata.txt"
else:
    url = f"https://raw.githubusercontent.com/nss-dev/nss/{source}/lib/ckfw/builtins/certdata.txt"
    text = urllib.request.urlopen(url).read().decode("utf-8")
    origin = f"NSS's lib/ckfw/builtins/certdata.txt at {source}"


def objects(lines):
    """certdata.txt's objects, each a dict of attribute to its value: the
    raw text after the type, or bytes for a MULTILINE_OCTAL one."""
    obj, key, octal = {}, None, None
    for line in lines:
        if line.startswith("#"):
            continue
        if octal is not None:
            if line == "END":
                obj[key] = bytes(octal)
                octal = None
            else:
                octal.extend(int(x, 8) for x in line.split("\\")[1:])
            continue
        if not line.strip():
            if obj:
                yield obj
            obj = {}
            continue
        parts = line.split(" ", 2)
        if len(parts) >= 2 and parts[1] == "MULTILINE_OCTAL":
            key, octal = parts[0], bytearray()
        elif len(parts) == 3:
            obj[parts[0]] = parts[2]
        elif len(parts) == 2:
            obj[parts[0]] = ""
    if obj:
        yield obj


def seconds(utc_time):
    """A UTCTime, YYMMDDHHMMSSZ, in seconds since the Unix epoch, its
    year read as RFC 5280 reads it."""
    assert len(utc_time) == 13 and utc_time.endswith("Z"), utc_time
    year = int(utc_time[0:2])
    year += 1900 if year >= 50 else 2000
    fields = [int(utc_time[i : i + 2]) for i in range(2, 12, 2)]
    return calendar.timegm((year, *fields, 0, 0, 0))


rows = []
for o in objects(text.splitlines()):
    after = o.get("CKA_NSS_SERVER_DISTRUST_AFTER")
    if o.get("CKA_CLASS") != "CKO_CERTIFICATE" or not isinstance(after, bytes):
        continue
    label = o.get("CKA_LABEL", "").strip('"')
    date = after.decode("ascii")
    rows.append((hashlib.sha256(o["CKA_VALUE"]).digest(), seconds(date), date, label))
rows.sort()

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "distrust_after.rs"), "w") as out:
    out.write(f"// Generated by scripts/gen-distrust-after.py from\n// {origin}. Don't edit.\n\n")
    out.write("/// Mozilla's roots with a server distrust-after date: the SHA-256 of\n")
    out.write("/// each one's DER, the date in seconds since the Unix epoch, and its\n")
    out.write("/// label.\n")
    out.write("pub(crate) const SERVER_DISTRUST_AFTER: &[([u8; 32], i64, &str)] = &[\n")
    for digest, at, date, label in rows:
        out.write("    (\n        [\n")
        for i in range(0, 32, 8):
            out.write("            " + " ".join(f"0x{b:02x}," for b in digest[i : i + 8]) + "\n")
        out.write(
            f"        ],\n        {at}, // {date}\n        {label!r},\n    ),\n".replace("'", '"')
        )
    out.write("];\n")
